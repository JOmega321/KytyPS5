"""Generate Windows-x64-ABI thunks for every Vulkan command in vulkan_core.h, from the Khronos registry.

Usage: gen_vk_thunks.py VULKAN_HEADERS_DIR OUT.c

AMD's provider DLL calls Vulkan with the Windows calling convention; the Linux loader's functions use the System V
one. Each thunk is an ms_abi function that forwards its arguments to the real function pointer, so the compiler
does the conversion. Output API (see vk_thunks.h): VkThunksBind, VkThunkLookup, VkThunkOverride, VkThunkReal.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def text(node):
    return "".join(node.itertext()).strip()


def for_vulkan(node):
    api = node.get("api")
    return api is None or "vulkan" in api.split(",")


def main():
    headers, out = Path(sys.argv[1]), Path(sys.argv[2])
    core = (headers / "include/vulkan/vulkan_core.h").read_text()
    root = ET.parse(headers / "registry/vk.xml").getroot()
    commands, aliases = {}, []
    for c in root.find("commands").findall("command"):
        if not for_vulkan(c):
            continue
        if c.get("alias"):
            aliases.append((c.get("name"), c.get("alias")))
            continue
        proto = c.find("proto")
        name = proto.find("name").text
        ret = text(proto)[: -len(name)].strip()
        params = [text(p) for p in c.findall("param") if for_vulkan(p)]
        # Allocation callbacks from the DLL would be Windows-ABI functions the driver cannot call: the driver gets NULL
        # (they only route host allocations).
        args = ["NULL" if p.find("type").text == "VkAllocationCallbacks" else p.find("name").text
                for p in c.findall("param") if for_vulkan(p)]
        commands[name] = (ret, params, args)
    names = [(n, n) for n in commands] + [(a, t) for a, t in aliases if t in commands]
    names = [(n, t) for n, t in names if ("PFN_%s)" % n) in core]
    lines = [
        "// Generated by tools/fsr4fg-vk/gen_vk_thunks.py from the Khronos Vulkan registry. Do not edit.",
        "#define VK_NO_PROTOTYPES",
        "#include <stddef.h>",
        "#include <string.h>",
        "#include <vulkan/vulkan_core.h>",
        '#include "vk_thunks.h"',
        "#define W __attribute__((ms_abi))",
        "const char* volatile vk_thunk_last;",
        "volatile unsigned long vk_thunk_calls;",
        "",
    ]
    for name, target in sorted(names):
        ret, params, args = commands[target]
        lines.append("static PFN_%s r_%s;" % (name, name))
        call = "r_%s(%s)" % (name, ", ".join(args))
        body = ("return %s;" % call) if ret != "void" else ("%s;" % call)
        lines.append("W static %s t_%s(%s) { vk_thunk_last = \"%s\"; vk_thunk_calls++; %s }"
                     % (ret, name, ", ".join(params) or "void", name, body))
    lines += [
        "",
        "typedef struct Thunk { const char* name; void** real; void* thunk; void* override; } Thunk;",
        "static Thunk thunks[] = {",
    ]
    for name, _ in sorted(names):
        lines.append('    {"%s", (void**)&r_%s, (void*)t_%s, 0},' % (name, name, name))
    lines += [
        "};",
        "static const unsigned thunk_count = sizeof(thunks) / sizeof(*thunks);",
        "static Thunk* find(const char* name) {",
        "    unsigned lo = 0, hi = thunk_count;",
        "    while (lo < hi) {",
        "        unsigned mid = (lo + hi) / 2;",
        "        int c = strcmp(thunks[mid].name, name);",
        "        if (!c) return &thunks[mid];",
        "        if (c < 0) lo = mid + 1; else hi = mid;",
        "    }",
        "    return 0;",
        "}",
        "unsigned VkThunksBind(PFN_vkGetInstanceProcAddr gipa, VkInstance instance, PFN_vkGetDeviceProcAddr gdpa, VkDevice device) {",
        "    unsigned bound = 0;",
        "    for (unsigned i = 0; i < thunk_count; i++) {",
        "        PFN_vkVoidFunction f = device && gdpa ? gdpa(device, thunks[i].name) : 0;",
        "        if (!f) f = gipa(instance, thunks[i].name);",
        "        *thunks[i].real = (void*)f;",
        "        bound += f != 0;",
        "    }",
        "    return bound;",
        "}",
        "void* VkThunkLookup(const char* name) {",
        "    Thunk* t = find(name);",
        "    if (!t || !*t->real) return 0;",
        "    return t->override ? t->override : t->thunk;",
        "}",
        "void* VkThunkReal(const char* name) { Thunk* t = find(name); return t ? *t->real : 0; }",
        "int VkThunkOverride(const char* name, void* replacement) { Thunk* t = find(name); if (!t) return 0; t->override = replacement; return 1; }",
        "unsigned VkThunkCount(void) { return thunk_count; }",
        "",
    ]
    out.write_text("\n".join(lines))
    print("%d thunks" % len(names))


if __name__ == "__main__":
    main()
